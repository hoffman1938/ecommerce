/**
 * Generates the demo seed as a single SQL file.
 *
 * Run on its own to inspect what the seed would do:
 *   node scripts/build-seed-sql.mjs
 *
 * No shebang here, unlike its sibling scripts. This module is the only one the
 * test suite imports (test/helpers/d1.ts builds the seed to populate an
 * in-memory database), and Vite hands the source to the runtime without
 * stripping a leading `#!`, which fails as `SyntaxError: Invalid or unexpected
 * token` and skips all 98 tests. Every entry point runs it as
 * `node scripts/…`, so the line bought nothing.
 *
 * Passwords never appear in the output — only PBKDF2 hashes, derived here with
 * exactly the parameters src/auth/password.ts verifies against, so a hash
 * written by Node authenticates in the Worker. The plaintext comes from the
 * environment; when it is absent a strong one is generated and printed once,
 * which keeps a working demo reachable without a password ever being committed.
 *
 * The generated file lands in .seed/ (git-ignored) rather than in the tree,
 * because a file full of password hashes is not something a public repository
 * needs to carry.
 */

import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { pbkdf2Sync, randomBytes } from 'node:crypto';
import { buildSeed } from './lib/seed-data.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const APP_ROOT = join(HERE, '..');
export const SEED_SQL_PATH = join(APP_ROOT, '.seed', 'seed.sql');

// Must match apps/edge/src/auth/password.ts exactly. 100,000 is workerd's
// ceiling for PBKDF2 — it rejects anything higher, and a hash seeded above it
// is one the Worker can never verify, so every seeded account would be locked
// out with "that email and password combination is not recognised".
const ITERATIONS = 100_000;
const KEY_BYTES = 32;
const SALT_BYTES = 16;

function hashPassword(plain) {
  const salt = randomBytes(SALT_BYTES);
  const derived = pbkdf2Sync(plain, salt, ITERATIONS, KEY_BYTES, 'sha256');
  return ['pbkdf2', 'sha256', ITERATIONS, salt.toString('base64'), derived.toString('base64')].join(
    '$',
  );
}

/**
 * A password strong enough that publishing the demo URL is not publishing the
 * demo. Base64 of 18 random bytes — 144 bits.
 */
const generatePassword = () => randomBytes(18).toString('base64url');

export function resolveDemoPasswords(env = process.env) {
  const generated = [];
  let admin = env.SEED_ADMIN_PASSWORD;
  let customer = env.SEED_CUSTOMER_PASSWORD;

  if (!admin) {
    admin = generatePassword();
    generated.push(['SEED_ADMIN_PASSWORD (admin@demo.local)', admin]);
  }
  if (!customer) {
    customer = generatePassword();
    generated.push(['SEED_CUSTOMER_PASSWORD (all other demo accounts)', customer]);
  }
  return { admin, customer, generated };
}

export function generateSeedSql(env = process.env) {
  const { admin, customer, generated } = resolveDemoPasswords(env);

  const { statements, counts } = buildSeed({
    adminPasswordHash: hashPassword(admin),
    customerPasswordHash: hashPassword(customer),
  });

  const header = [
    '-- Outlet Marketplace — demo seed for Cloudflare D1.',
    '-- Generated by apps/edge/scripts/build-seed-sql.mjs. Do not edit by hand.',
    '--',
    '-- Every statement is idempotent: re-running this file adds nothing and',
    '-- changes nothing except the rows the seed explicitly owns.',
    '--',
    '-- Contains password *hashes*, never passwords.',
    '',
  ].join('\n');

  return { sql: `${header}\n${statements.join('\n')}\n`, counts, generated };
}

/**
 * Statements per file when the seed is written for `wrangler d1 execute`.
 *
 * The whole seed is about 4,700 statements and 1.9 MB. Handing that to
 * wrangler in one call crashes its local workerd runtime outright, and the
 * remote endpoint has its own request-size limit — so it is written as an
 * ordered set of files instead, each comfortably inside both.
 *
 * Order is preserved across files, which is what keeps foreign keys satisfied:
 * a chunk boundary is only ever between two statements that were already
 * consecutive.
 */
const STATEMENTS_PER_CHUNK = 400;

export function writeSeedSql(env = process.env) {
  const { admin, customer, generated } = resolveDemoPasswords(env);
  const { statements, counts } = buildSeed({
    adminPasswordHash: hashPassword(admin),
    customerPasswordHash: hashPassword(customer),
  });

  const dir = dirname(SEED_SQL_PATH);
  mkdirSync(dir, { recursive: true });

  // Clear any chunks from a previous, possibly longer, run so a shrinking
  // seed cannot leave stale files behind for the applier to pick up.
  for (const file of readdirSync(dir).filter((name) => /^seed\.\d+\.sql$/.test(name))) {
    rmSync(join(dir, file));
  }

  const paths = [];
  let bytes = 0;
  const chunkCount = Math.ceil(statements.length / STATEMENTS_PER_CHUNK);

  for (let index = 0; index < chunkCount; index += 1) {
    const chunk = statements.slice(
      index * STATEMENTS_PER_CHUNK,
      (index + 1) * STATEMENTS_PER_CHUNK,
    );
    const body = `${seedHeader(index + 1, chunkCount)}\n${chunk.join('\n')}\n`;
    const path = join(dir, `seed.${String(index + 1).padStart(3, '0')}.sql`);
    writeFileSync(path, body, 'utf8');
    paths.push(path);
    bytes += Buffer.byteLength(body);
  }

  // A single combined file as well, for reading and for `db:sql`.
  const combined = `${seedHeader(1, 1)}\n${statements.join('\n')}\n`;
  writeFileSync(SEED_SQL_PATH, combined, 'utf8');

  return { path: SEED_SQL_PATH, paths, counts, generated, bytes, statements: statements.length };
}

const seedHeader = (part, total) =>
  [
    '-- Outlet Marketplace — demo seed for Cloudflare D1.',
    `-- Generated by apps/edge/scripts/build-seed-sql.mjs. Part ${part} of ${total}.`,
    '-- Do not edit by hand.',
    '--',
    '-- Every statement is idempotent: re-running adds nothing and changes',
    '-- nothing except the rows the seed explicitly owns.',
    '--',
    '-- Contains password *hashes*, never passwords.',
    '',
  ].join('\n');

export function reportCounts(counts) {
  const rows = Object.entries(counts).sort(([a], [b]) => a.localeCompare(b));
  const width = Math.max(...rows.map(([key]) => key.length));
  for (const [key, value] of rows) {
    console.log(`  ${key.padEnd(width)}  ${String(value).padStart(5)}`);
  }
}

// Run directly (not imported): write the file and report.
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const result = writeSeedSql();
  console.log(`Wrote ${result.path} (${(result.bytes / 1024).toFixed(0)} KB)\n`);
  reportCounts(result.counts);
  if (result.generated.length > 0) {
    console.log('\nGenerated demo passwords — copy these now, they are not stored:\n');
    for (const [label, value] of result.generated) console.log(`  ${label}\n    ${value}`);
    console.log('\nSet SEED_ADMIN_PASSWORD / SEED_CUSTOMER_PASSWORD to choose your own.');
  }
}
